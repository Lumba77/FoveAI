def _inventory_search_blob(inventory_rows: list[dict[str, Any]]) -> set[str]:
    """Build a set of searchable tokens from the inventory for fast comparison."""
    tokens: set[str] = set()
    for row in inventory_rows:
        label = row.get("label", "")
        notes = row.get("notes", "")
        h2 = row.get("h2_title", "")
        # Tokenize on path-like strings and camelCase/PascalCase words
        text = f"{label} {notes} {h2}".lower()
        # Extract file paths
        for m in re.finditer(r"[\w/\\.]+\.(py|ps1|json|md|gd|yml|yaml|sh)", text):
            tokens.add(m.group(0).replace("\\", "/"))
        # Extract module names
        for m in re.finditer(r"[A-Za-z_][A-Za-z0-9_]+", text):
            tokens.add(m.group(0).lower())
    return tokens


# ── Drone: Mapper ──────────────────────────────────────────────────────────────


async def _mapper_drone(
    scan_dirs: list[str], inventory_tokens: set[str]
) -> DroneReport:
    """Scan source files for classes, functions, endpoints, services."""
    _update_drone("mapper", "scanning", "repo_root", "Mapping codebase structure...")
    start = time.time()
    features: list[DiscoveredFeature] = []
    files_scanned = 0

    skip_re = [re.compile(p) for p in SKIP_PATTERNS]

    for rel_dir in scan_dirs:
        base = REPO_ROOT / rel_dir
        if not base.is_dir():
            continue
        for fp in base.rglob("*"):
            # Skip filtered paths
            path_str = str(fp)
            if any(r.search(path_str) for r in skip_re):
                continue
            if fp.is_dir():
                continue

            files_scanned += 1
            rel = fp.relative_to(REPO_ROOT).as_posix()

            # Python analysis
            if fp.suffix == ".py":
                features.extend(_scan_python_file(fp, rel, inventory_tokens))
            # PowerShell analysis
            elif fp.suffix == ".ps1":
                features.extend(_scan_powershell_file(fp, rel, inventory_tokens))
            # Docker Compose analysis
            elif fp.name == "docker-compose.yml" or fp.suffix in (".yml", ".yaml"):
                features.extend(_scan_yaml_file(fp, rel, inventory_tokens))
            # Markdown docs
            elif fp.suffix == ".md" and fp.name != "FEATURE_INVENTORY.md":
                # Check if this markdown file is referenced in inventory
                if (
                    rel not in inventory_tokens
                    and fp.stem.lower() not in inventory_tokens
                ):
                    features.append(
                        DiscoveredFeature(
                            source_file=rel,
                            feature_type="doc",
                            name=fp.stem,
                            description="Documentation file not referenced in inventory",
                            evidence=f"Found at {rel}",
                        )
                    )
            # Godot scripts
            elif fp.suffix == ".gd":
                if (
                    rel not in inventory_tokens
                    and fp.stem.lower() not in inventory_tokens
                ):
                    features.append(
                        DiscoveredFeature(
                            source_file=rel,
                            feature_type="script",
                            name=fp.stem,
                            description="Godot script not indexed",
                            evidence=f"Found at {rel}",
                        )
                    )

            # Brief yield every 50 files to not block event loop
            if files_scanned % 50 == 0:
                _update_drone(
                    "mapper", "scanning", rel_dir, f"Scanned {files_scanned} files..."
                )
                await asyncio.sleep(0)

    _update_drone(
        "mapper",
        "returning",
        "base",
        f"Mapped {files_scanned} files, found {len(features)} candidates.",
    )
    end = time.time()
    return DroneReport(
        drone_id="mapper",
        role="Mapper",
        scan_start=start,
        scan_end=end,
        features=features,
        files_scanned=files_scanned,
    )


def _scan_python_file(
    fp: Path, rel: str, inventory_tokens: set[str]
) -> list[DiscoveredFeature]:
    """Extract features from a Python file."""
    features: list[DiscoveredFeature] = []
    try:
        text = fp.read_text(encoding="utf-8", errors="ignore")
        lines = text.splitlines()
    except Exception:
        return features

    # FastAPI endpoints
    for i, line in enumerate(lines):
        m = re.search(
            r"@app\.(get|post|put|delete|patch)\s*\(\s*[\"']([^\"']+)[\"']", line
        )
        if m:
            method, path = m.group(1).upper(), m.group(2)
            # Find the function name on the next non-empty non-comment line
            func_name = "unknown"
            for j in range(i + 1, min(i + 5, len(lines))):
                fm = re.match(r"\s*async\s+def\s+(\w+)|\s*def\s+(\w+)", lines[j])
                if fm:
                    func_name = fm.group(1) or fm.group(2)
                    break
            key = f"{method} {path}"
            indexed = (
                key.lower() in inventory_tokens
                or func_name.lower() in inventory_tokens
                or rel in inventory_tokens
            )

            # Filter: only meaningful features
            if not indexed and _is_meaningful_feature(
                key, rel, f"FastAPI endpoint `{func_name}`", "endpoint"
            ):
                features.append(
                    DiscoveredFeature(
                        source_file=rel,
                        feature_type="endpoint",
                        name=f"{method} {path}",
                        description=f"FastAPI endpoint `{func_name}`",
                        evidence=f"Line {i + 1}: {line.strip()[:120]}",
                    )
                )

    # Class definitions
    for i, line in enumerate(lines):
        m = re.match(r"\s*class\s+(\w+)", line)
        if m:
            cls_name = m.group(1)
            if cls_name.startswith("_"):
                continue
            indexed = cls_name.lower() in inventory_tokens or rel in inventory_tokens

            # Filter: only meaningful classes
            desc = f"Python class `{cls_name}`"
            if not indexed and _is_meaningful_feature(cls_name, rel, desc, "class"):
                features.append(
                    DiscoveredFeature(
                        source_file=rel,
                        feature_type="class",
                        name=cls_name,
                        description=f"Python class `{cls_name}`",
                        evidence=f"Line {i + 1}: {line.strip()[:120]}",
                    )
                )

    # TODO / FIXME / HACK comments as potential features
    for i, line in enumerate(lines):
        m = re.search(
            r"(TODO|FIXME|HACK|XXX|NOTE:)\s*[:-]?\s*(.+)", line, re.IGNORECASE
        )
        if m:
            tag, desc = m.group(1).upper(), m.group(2).strip()
            if len(desc) > 10 and "unindexed" not in desc.lower():
                features.append(
                    DiscoveredFeature(
                        source_file=rel,
                        feature_type="todo",
                        name=f"{tag} in {Path(rel).name}",
                        description=desc[:200],
                        tier_guess="D",
                        evidence=f"Line {i + 1}: {line.strip()[:200]}",
                    )
                )

    return features


def _scan_powershell_file(
    fp: Path, rel: str, inventory_tokens: set[str]
) -> list[DiscoveredFeature]:
    """Extract features from a PowerShell file."""
    features: list[DiscoveredFeature] = []
    try:
        text = fp.read_text(encoding="utf-8", errors="ignore")
        lines = text.splitlines()
    except Exception:
        return features

    for i, line in enumerate(lines):
        # Function definitions
        m = re.match(r"\s*function\s+([-\w]+)", line)
        if m:
            func_name = m.group(1)
            indexed = func_name.lower() in inventory_tokens or rel in inventory_tokens
            if not indexed:
                features.append(
                    DiscoveredFeature(
                        source_file=rel,
                        feature_type="function",
                        name=func_name,
                        description=f"PowerShell function `{func_name}`",
                        evidence=f"Line {i + 1}: {line.strip()[:120]}",
                    )
                )

        # TODO / FIXME
        m = re.search(r"#\s*(TODO|FIXME|HACK|XXX)\s*[:-]?\s*(.+)", line, re.IGNORECASE)
        if m:
            tag, desc = m.group(1).upper(), m.group(2).strip()
            if len(desc) > 10:
                features.append(
                    DiscoveredFeature(
                        source_file=rel,
                        feature_type="todo",
                        name=f"{tag} in {Path(rel).name}",
                        description=desc[:200],
                        tier_guess="D",
                        evidence=f"Line {i + 1}: {line.strip()[:200]}",
                    )
                )

    return features


def _scan_yaml_file(
    fp: Path, rel: str, inventory_tokens: set[str]
) -> list[DiscoveredFeature]:
    """Extract Docker Compose services or other YAML-defined features."""
    features: list[DiscoveredFeature] = []
    try:
        text = fp.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return features

    # Docker service names
    for m in re.finditer(r"^\s{2}(\w+):\s*$", text, re.MULTILINE):
        svc = m.group(1)
        if svc in ("services", "volumes", "networks", "configs", "secrets"):
            continue
        if svc.lower() not in inventory_tokens and rel not in inventory_tokens:
            features.append(
                DiscoveredFeature(
                    source_file=rel,
                    feature_type="service",
                    name=svc,
                    description=f"Docker service `{svc}`",
                    evidence=f"Found in {rel}",
                )
            )

    return features


# ── Drone: Archivist ─────────────────────────────────────────────────────────


async def _archivist_drone(inventory_rows: list[dict[str, Any]]) -> DroneReport:
    """Analyze inventory structure — find gaps, duplicates, orphan sections."""
    _update_drone(
        "archivist",
        "analyzing",
        "inventory",
        "Cross-referencing inventory structure...",
    )
    start = time.time()

    features: list[DiscoveredFeature] = []
    notes = []

    # Check for empty categories
    category_counts: dict[str, int] = {}
    for row in inventory_rows:
        cat = row.get("category", "other")
        category_counts[cat] = category_counts.get(cat, 0) + 1

    expected_cats = {
        "docker",
        "web",
        "backend",
        "godot",
        "mobile",
        "tests",
        "ops",
        "parity",
        "service",
        "memory",
        "install",
        "roadmap",
        "meta",
        "architecture",
        "troubleshooters",
    }
    for cat in expected_cats:
        if category_counts.get(cat, 0) == 0:
            features.append(
                DiscoveredFeature(
                    source_file="FEATURE_INVENTORY.md",
                    feature_type="gap",
                    name=f"Empty category: {cat}",
                    description=f"No entries found for '{cat}' — may need audit",
                    tier_guess="B",
                    evidence=f"Category '{cat}' has 0 rows",
                )
            )

    # Check for files referenced but missing from disk
    for row in inventory_rows:
        label = row.get("label", "")
        for m in re.finditer(r"[\w/\\.]+\.(py|ps1|json|md|gd|yml|yaml|sh)", label):
            path_str = m.group(0).replace("\\", "/")
            if not (REPO_ROOT / path_str).is_file():
                features.append(
                    DiscoveredFeature(
                        source_file="FEATURE_INVENTORY.md",
                        feature_type="orphan",
                        name=f"Missing: {path_str}",
                        description=f"Inventory references `{path_str}` but file not found",
                        tier_guess="B",
                        evidence=f"Row: {label[:100]}",
                    )
                )

    notes.append(
        f"Inventory has {len(inventory_rows)} indexed features across {len(category_counts)} categories."
    )

    _update_drone(
        "archivist",
        "returning",
        "base",
        f"Analyzed {len(inventory_rows)} inventory rows.",
    )
    end = time.time()
    return DroneReport(
        drone_id="archivist",
        role="Archivist",
        scan_start=start,
        scan_end=end,
        features=features,
        files_scanned=len(inventory_rows),
        notes="; ".join(notes),
    )


# ── Drone: Auditor ────────────────────────────────────────────────────────────


async def _auditor_drone(
    scan_dirs: list[str], inventory_tokens: set[str]
) -> DroneReport:
    """Audit for security patterns, configuration files, and hidden capabilities."""
    _update_drone(
        "auditor", "scanning", "config", "Auditing configs and credentials..."
    )
    start = time.time()
    features: list[DiscoveredFeature] = []

    # Check for .env files not in inventory
    for env_file in REPO_ROOT.rglob(".env*"):
        rel = env_file.relative_to(REPO_ROOT).as_posix()
        if "__pycache__" in rel or ".venv" in rel:
            continue
        if rel not in inventory_tokens and env_file.name not in inventory_tokens:
            features.append(
                DiscoveredFeature(
                    source_file=rel,
                    feature_type="config",
                    name=env_file.name,
                    description="Environment config not referenced in inventory",
                    evidence=f"Found at {rel}",
                )
            )

    # Check for requirements files
    for req_file in REPO_ROOT.rglob("requirements*.txt"):
        rel = req_file.relative_to(REPO_ROOT).as_posix()
        if ".venv" in rel:
            continue
        if rel not in inventory_tokens:
            features.append(
                DiscoveredFeature(
                    source_file=rel,
                    feature_type="config",
                    name=req_file.name,
                    description="Dependency file not indexed",
                    evidence=f"Found at {rel}",
                )
            )

    _update_drone(
        "auditor", "returning", "base", f"Audited configs, found {len(features)} items."
    )
    end = time.time()
    return DroneReport(
        drone_id="auditor",
        role="Auditor",
        scan_start=start,
        scan_end=end,
        features=features,
        files_scanned=0,
        notes="Config audit complete",
    )


# ── Director ──────────────────────────────────────────────────────────────────


async def _director_synthesize(
    mapper_report: DroneReport,
    archivist_report: DroneReport,
    auditor_report: DroneReport,
    inventory_rows: list[dict[str, Any]],
    model: str,
    host: str,
) -> DirectorProposal:
    """Synthesize drone reports into actionable inventory proposals."""
    _update_drone("director", "synthesizing", "base", "Analyzing drone reports...")

    mission_id = hashlib.sha256(
        f"{time.time()}{mapper_report.files_scanned}".encode()
    ).hexdigest()[:16]

    # Aggregate all features
    all_features = (
        mapper_report.features + archivist_report.features + auditor_report.features
    )

    # Deduplicate by name+file
    seen: set[str] = set()
    unique_features: list[DiscoveredFeature] = []
    for f in all_features:
        key = f"{f.source_file}:{f.name}:{f.feature_type}"
        if key not in seen:
            seen.add(key)
            unique_features.append(f)

    # Group by type
    by_type: dict[str, list[DiscoveredFeature]] = {}
    for f in unique_features:
        by_type.setdefault(f.feature_type, []).append(f)

    # Build structured proposals
    new_features: list[dict[str, Any]] = []
    for f in unique_features:
        # Guess category
        cat = _guess_category(f.source_file, f.feature_type)
        tier = f.tier_guess
        # Upgrade tier for endpoints/classes
        if f.feature_type in ("endpoint", "class") and tier == "C":
            tier = "B"
        new_features.append(
            {
                "source_file": f.source_file,
                "feature_type": f.feature_type,
                "name": f.name,
                "description": f.description,
                "proposed_category": cat,
                "proposed_tier": tier,
                "evidence": f.evidence,
            }
        )

    gaps = [f.name for f in unique_features if f.feature_type == "gap"]

    # Build summary
    summary = (
        f"Discovery mission {mission_id}: "
        f"scanned {mapper_report.files_scanned} files, "
        f"found {len(unique_features)} unindexed items "
        f"({len(by_type.get('endpoint', []))} endpoints, "
        f"{len(by_type.get('class', []))} classes, "
        f"{len(by_type.get('todo', []))} TODOs, "
        f"{len(by_type.get('function', []))} functions, "
        f"{len(by_type.get('service', []))} services, "
        f"{len(by_type.get('config', []))} configs). "
        f"{len(gaps)} category gaps detected."
    )

    # Build raw reports for persistence
    raw_reports = [
        {
            "drone_id": r.drone_id,
            "role": r.role,
            "files_scanned": r.files_scanned,
            "features_found": len(r.features),
            "notes": r.notes,
            "features": [
                {
                    "source_file": f.source_file,
                    "feature_type": f.feature_type,
                    "name": f.name,
                    "description": f.description,
                    "tier_guess": f.tier_guess,
                    "evidence": f.evidence,
                }
                for f in r.features
            ],
        }
        for r in (mapper_report, archivist_report, auditor_report)
    ]

    proposal = DirectorProposal(
        mission_id=mission_id,
        timestamp=datetime.now(datetime.UTC).isoformat().replace("+00:00", "Z"),
        summary=summary,
        new_features=new_features,
        gaps=gaps,
        confidence=min(0.95, 0.3 + 0.05 * len(new_features)),
        raw_drone_reports=raw_reports,
    )

    _update_drone(
        "director", "idle", "base", f"Mission complete. {len(new_features)} proposals."
    )
    return proposal


def _guess_category(source_file: str, feature_type: str) -> str:
    """Map a source file path to an inventory category."""
    path = source_file.lower()
    if "docker" in path or "compose" in path:
        return "docker"
    if path.startswith("frontend/web_vessel") or path.startswith("frontend/web"):
        return "web"
    if (
        path.startswith("frontend/xr")
        or path.startswith("frontend/vr")
        or "godot" in path
    ):
        return "godot"
    if path.startswith("frontend/mobile"):
        return "mobile"
    if "test" in path or path.startswith("scripts/autotest"):
        return "tests"
    if "sentry" in path or "guardian" in path or "install" in path or "service" in path:
        return "service"
    if path.startswith("backend/memory") or "consent" in path:
        return "memory"
    if "install" in path or "uninstall" in path:
        return "install"
    if path.startswith("backend/creativity"):
        return "creative"
    if path.startswith("backend"):
        return "backend"
    if path.startswith("frontend"):
        return "ops"
    if "scripts" in path:
        return "ops"
    if feature_type == "endpoint":
        return "web"
    if feature_type == "service":
        return "docker"
    return "other"


# ── Persistence ─────────────────────────────────────────────────────────────────


def _save_report(proposal: DirectorProposal) -> Path:
    """Persist a Director proposal to .logs/discovery_reports/."""
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(datetime.UTC).strftime("%Y%m%d_%H%M%S")
    filename = f"{ts}_{proposal.mission_id}.json"
    path = REPORTS_DIR / filename

    payload = {
        "mission_id": proposal.mission_id,
        "timestamp": proposal.timestamp,
        "summary": proposal.summary,
        "new_features": proposal.new_features,
        "gaps": proposal.gaps,
        "confidence": proposal.confidence,
        "drone_reports": proposal.raw_drone_reports,
    }

    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")
    logger.info(f"Discovery report saved: {path}")
    return path


def list_discovery_reports(limit: int = 20) -> list[dict[str, Any]]:
    """List persisted discovery reports, newest first."""
    if not REPORTS_DIR.is_dir():
        return []
    reports = []
    for p in sorted(REPORTS_DIR.glob("*.json"), key=lambda x: x.name, reverse=True):
        try:
            data = json.loads(p.read_text(encoding="utf-8"))
            data["_filename"] = p.name
            reports.append(data)
        except Exception:
            continue
    return reports[:limit]


def get_latest_discovery_notification() -> dict[str, Any] | None:
    """Get the most recent discovery report formatted as a notification."""
    reports = list_discovery_reports(limit=1)
    if not reports:
        return None
    r = reports[0]
    return {
        "id": r.get("mission_id", "unknown"),
        "type": "discovery",
        "title": f"Discovery Report: {len(r.get('new_features', []))} unindexed features found",
        "summary": r.get("summary", "")[:200],
        "timestamp": r.get("timestamp", ""),
        "count": len(r.get("new_features", [])),
        "gaps": len(r.get("gaps", [])),
        "filename": r.get("_filename", ""),
    }


