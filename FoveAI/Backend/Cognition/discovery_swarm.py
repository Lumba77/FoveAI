# ── Main entry point ───────────────────────────────────────────────────────────


async def execute_discovery_mission(
    duration_minutes: int = 30,
    use_director: bool = True,
    auto_apply: Optional[bool] = None,
    session_summary: Optional[str] = None,
) -> dict[str, Any]:
    """Launch a discovery swarm mission.

    Args:
        duration_minutes: Max time for discovery scan
        use_director: If True, send results to cloud Director Manager
        auto_apply: If True, auto-apply Director's indexing decisions
                   (overrides LUMAX_DIRECTOR_AUTO_APPLY env var)
    """
    global DISCOVERY_STATE
    DISCOVERY_STATE["active"] = True
    DISCOVERY_STATE["start_time"] = time.time()
    DISCOVERY_STATE["duration_min"] = duration_minutes
    DISCOVERY_STATE["progress_pct"] = 0
    DISCOVERY_STATE["results"] = {}

    logger.info(f"🔭 Discovery Swarm launching (max {duration_minutes} min)...")

    # PHASE 1: Load inventory
    _update_drone("director", "planning", "base", "Loading FEATURE_INVENTORY.md...")
    inventory_rows = _load_inventory_flat()
    inventory_tokens = _inventory_search_blob(inventory_rows)
    _update_drone(
        "director",
        "planning",
        "base",
        f"Inventory loaded: {len(inventory_rows)} features.",
    )

    # PHASE 2: Dispatch drones
    _update_drone(
        "director", "directing", "base", "Dispatching Mapper, Archivist, Auditor..."
    )

    mapper_task = asyncio.create_task(_mapper_drone(SCAN_DIRS, inventory_tokens))
    archivist_task = asyncio.create_task(_archivist_drone(inventory_rows))
    auditor_task = asyncio.create_task(_auditor_drone(SCAN_DIRS, inventory_tokens))

    # Progress updates while drones work
    total_timeout = duration_minutes * 60
    elapsed = 0.0
    while not (mapper_task.done() and archivist_task.done() and auditor_task.done()):
        await asyncio.sleep(1.0)
        elapsed += 1.0
        pct = min(95, int((elapsed / max(total_timeout * 0.3, 1.0)) * 100))
        DISCOVERY_STATE["progress_pct"] = pct
        if elapsed > total_timeout:
            logger.warning("Discovery mission timeout — forcing completion.")
            mapper_task.cancel()
            archivist_task.cancel()
            auditor_task.cancel()
            break

    # Collect results (handle cancellations gracefully)
    mapper_report = (
        mapper_task.result()
        if not mapper_task.cancelled()
        else DroneReport(
            drone_id="mapper", role="Mapper", scan_start=0, scan_end=0, notes="TIMEOUT"
        )
    )
    archivist_report = (
        archivist_task.result()
        if not archivist_task.cancelled()
        else DroneReport(
            drone_id="archivist",
            role="Archivist",
            scan_start=0,
            scan_end=0,
            notes="TIMEOUT",
        )
    )
    auditor_report = (
        auditor_task.result()
        if not auditor_task.cancelled()
        else DroneReport(
            drone_id="auditor",
            role="Auditor",
            scan_start=0,
            scan_end=0,
            notes="TIMEOUT",
        )
    )

    DISCOVERY_STATE["progress_pct"] = 98
    _update_drone("director", "synthesizing", "base", "Synthesizing final proposal...")

    # Aggregate all unindexed features for Director
    all_features = (
        mapper_report.features + archivist_report.features + auditor_report.features
    )
    unindexed_features = [
        {
            "source_file": f.source_file,
            "feature_type": f.feature_type,
            "name": f.name,
            "description": f.description,
            "proposed_category": _guess_category(f.source_file, f.feature_type),
            "proposed_tier": f.tier_guess,
            "evidence": f.evidence,
        }
        for f in all_features
    ]

    # PHASE 3: Director analysis (cloud-based with deepseek-v4-pro:1m)
    director_result = None
    if use_director and DIRECTOR_MANAGER_AVAILABLE:
        _update_drone(
            "director", "consulting", "cloud", "Contacting Director Manager..."
        )
        logger.info(
            "📡 Sending discovery report to Director Manager (deepseek-v4-pro:1m)..."
        )

        try:
            director_result = await run_director_analysis(
                mission_id=hashlib.sha256(f"{time.time()}".encode()).hexdigest()[:16],
                discovery_summary=(
                    f"scanned {mapper_report.files_scanned} files, "
                    f"found {len(unindexed_features)} unindexed items"
                ),
                files_scanned=mapper_report.files_scanned,
                unindexed_features=unindexed_features,
                current_inventory_rows=inventory_rows,
                auto_apply=auto_apply,
                session_summary=session_summary,
            )

            if director_result and director_result.get("success"):
                _update_drone(
                    "director",
                    "analyzed",
                    "cloud",
                    f"Director indexed {director_result.get('features_to_index', 0)} features",
                )
                logger.info(
                    f"📡 Director analysis complete: "
                    f"{director_result.get('features_to_index', 0)} to index, "
                    f"{director_result.get('features_skipped', 0)} skipped"
                )
            else:
                logger.warning("Director analysis returned no result")
        except Exception as e:
            logger.error(f"Director analysis failed: {e}")
            _update_drone("director", "error", "cloud", f"Director failed: {e}")

    # PHASE 4: Local synthesis fallback (if Director unavailable or disabled)
    if not director_result:
        local_model = os.getenv("FoveAI_SENTRY_SOLVER_MODEL", "qwen3.5-0.5b").strip()
        local_host = (
            os.getenv(
                "FoveAI_FALLBACK_BASE_URL",
                os.getenv(
                    "FoveAI_BACKUP_BASE_URL",
                    os.getenv("OLLAMA_HOST", "http://localhost:11434"),
                ),
            )
            .strip()
            .rstrip("/")
        )

        proposal = await _director_synthesize(
            mapper_report,
            archivist_report,
            auditor_report,
            inventory_rows,
            local_model,
            local_host,
        )
        report_path = _save_report(proposal)

        final = {
            "mission_id": proposal.mission_id,
            "timestamp": proposal.timestamp,
            "summary": proposal.summary,
            "new_features_count": len(proposal.new_features),
            "gaps_count": len(proposal.gaps),
            "confidence": proposal.confidence,
            "report_file": str(report_path.relative_to(REPO_ROOT)),
            "new_features": proposal.new_features[:50],
            "gaps": proposal.gaps,
            "director_used": False,
        }
    else:
        # Use Director result
        final = {
            "mission_id": director_result["mission_id"],
            "timestamp": datetime.now(datetime.UTC).isoformat().replace("+00:00", "Z"),
            "summary": director_result.get("summary", ""),
            "new_features_count": director_result.get("features_to_index", 0),
            "features_skipped": director_result.get("features_skipped", 0),
            "features_analyzed": director_result.get("features_analyzed", 0),
            "gaps_count": 0,
            "confidence": director_result.get("confidence", 0.5),
            "report_file": "",
            "director_used": True,
            "director_model": director_result.get("model_used", "unknown"),
            "auto_applied": bool(
                director_result.get("apply_result", {}).get("success")
            ),
            "entries_added": director_result.get("apply_result", {}).get(
                "entries_added", 0
            ),
        }

        # Save Director result to reports
        director_report_path = _save_director_report(director_result)
        final["director_report_file"] = director_report_path

    DISCOVERY_STATE["progress_pct"] = 100
    DISCOVERY_STATE["results"] = final
    DISCOVERY_STATE["active"] = False

    # Reset drone states after delay
    await asyncio.sleep(2.0)
    for d in DISCOVERY_STATE["drones"]:
        _update_drone(d, "idle", "base", "Awaiting orders")

    logger.info(f"🔭 Discovery mission complete: {final.get('summary', '')}")
    return final


def _save_director_report(director_result: dict[str, Any]) -> str:
    """Save Director analysis result to discovery reports folder."""
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    ts = datetime.now(datetime.UTC).strftime("%Y%m%d_%H%M%S")
    mission_id = director_result.get("mission_id", "unknown")
    filename = f"{ts}_{mission_id}_director.json"
    path = REPORTS_DIR / filename

    path.write_text(
        json.dumps(director_result, indent=2, ensure_ascii=False), encoding="utf-8"
    )
    logger.info(f"Director report saved: {path}")
    return str(path.relative_to(REPO_ROOT))
