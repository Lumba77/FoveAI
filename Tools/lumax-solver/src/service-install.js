/**
 * foveai-solver service installer
 *
 * Cross-platform system service installation:
 *   Windows  → Windows Task Scheduler (runs at logon, restarts on failure)
 *   macOS    → launchd plist in ~/Library/LaunchAgents/
 *   Linux    → systemd user unit in ~/.config/systemd/user/
 *
 * Usage (via CLI):
 *   foveai-solver service install
 *   foveai-solver service remove
 *   foveai-solver service status
 *   foveai-solver service start
 *   foveai-solver service stop
 *
 * Or import for use in setup.js:
 *   import { install, remove, status } from './service-install.js';
 */

import fs from 'fs';
import os from 'os';
import path from 'path';
import { execSync, spawnSync } from 'child_process';
import { fileURLToPath } from 'url';

const __dirname  = path.dirname(fileURLToPath(import.meta.url));
const SOLVER_JS  = path.resolve(__dirname, '..', 'foveai-solver.js');
const NODE_BIN   = process.execPath;
const PLATFORM   = process.platform;
const SERVICE_ID = 'foveai-solver';
const SERVE_PORT = 8113;

// ─── Helpers ──────────────────────────────────────────────────────────────────
function run(cmd, opts = {}) {
    return spawnSync(cmd, { shell: true, encoding: 'utf-8', stdio: 'pipe', ...opts });
}

function green(s)  { return `\x1b[32m${s}\x1b[0m`; }
function yellow(s) { return `\x1b[33m${s}\x1b[0m`; }
function cyan(s)   { return `\x1b[36m${s}\x1b[0m`; }

// ─── Windows ──────────────────────────────────────────────────────────────────
const WIN_TASK_NAME  = 'Lumax-Solver-Guardian';
const WIN_PS1        = path.resolve(__dirname, '..', 'guardian.ps1');

function writeWindowsPs1() {
    // Write a minimal PS1 supervisor that restarts node if it crashes
    const nodeBinEsc    = NODE_BIN.replace(/\\/g, '\\\\');
    const solverJsEsc   = SOLVER_JS.replace(/\\/g, '\\\\');
    const userProfile   = '%USERPROFILE%';
    const content = [
        '# Lumax Solver Guardian — Auto-generated by service-install.js',
        '# Restarts the solver service on crash.',
        `$NodeBin = "${nodeBinEsc}";`,
        `$SolverJs = "${solverJsEsc}";`,
        'while ($true) {',
        '    $proc = Start-Process -FilePath $NodeBin -ArgumentList """$SolverJs""", "--service" -PassThru -NoNewWindow;',
        '    $proc.WaitForExit();',
        '    $exit = $proc.ExitCode;',
        '    if ($exit -eq 0) { break; }',
        '    $stamp = Get-Date -Format "o";',
        `    Add-Content -Path "$env:USERPROFILE\\.foveai\\guardian-crash.log" -Value "$stamp exited $exit restarting in 5s";`,
        '    Start-Sleep -Seconds 5;',
        '}',
    ].join('\n');
    fs.writeFileSync(WIN_PS1, content, 'utf-8');
}


async function installWindows() {
    writeWindowsPs1();
    const cmd = [
        `schtasks /Create /F /TN "${WIN_TASK_NAME}"`,
        `/SC ONLOGON`,
        `/TR "powershell.exe -NoProfile -WindowStyle Hidden -File \\"${WIN_PS1}\\""`,
        `/RL HIGHEST`,
        `/RU "${os.userInfo().username}"`,
    ].join(' ');
    const r = run(cmd);
    if (r.status !== 0) throw new Error(r.stderr || r.stdout || 'schtasks failed');
    console.log(`${green('✅')} Scheduled Task "${WIN_TASK_NAME}" registered.`);
    // Start it immediately
    run(`schtasks /Run /TN "${WIN_TASK_NAME}"`);
    console.log(`${green('✅')} Guardian started.`);
}

async function removeWindows() {
    run(`schtasks /Delete /F /TN "${WIN_TASK_NAME}"`);
    console.log(`${yellow('🗑️')} Scheduled Task "${WIN_TASK_NAME}" removed.`);
}

async function statusWindows() {
    const r = run(`schtasks /Query /TN "${WIN_TASK_NAME}" /FO LIST`);
    if (r.status !== 0) { console.log('Service not installed.'); return; }
    console.log(r.stdout);
    // Ping the HTTP endpoint
    await pingService();
}

async function startWindows() {
    run(`schtasks /Run /TN "${WIN_TASK_NAME}"`);
    console.log(`${green('▶️')} Guardian started.`);
}

async function stopWindows() {
    run(`taskkill /F /FI "WINDOWTITLE eq Lumax*" /T`);
    console.log(`${yellow('⏹️')} Guardian stopped.`);
}

// ─── macOS ────────────────────────────────────────────────────────────────────
const MACOS_PLIST_DIR  = path.join(os.homedir(), 'Library', 'LaunchAgents');
const MACOS_PLIST_PATH = path.join(MACOS_PLIST_DIR, `com.foveai.solver.plist`);

function writeMacosPlist() {
    const plist = `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>com.foveai.solver</string>
    <key>ProgramArguments</key>
    <array>
        <string>${NODE_BIN}</string>
        <string>${SOLVER_JS}</string>
        <string>--service</string>
    </array>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <true/>
    <key>StandardOutPath</key>
    <string>${os.homedir()}/.foveai/guardian.log</string>
    <key>StandardErrorPath</key>
    <string>${os.homedir()}/.foveai/guardian-error.log</string>
    <key>EnvironmentVariables</key>
    <dict>
        <key>FoveAI_SERVE_PORT</key>
        <string>${SERVE_PORT}</string>
    </dict>
</dict>
</plist>`;
    fs.mkdirSync(MACOS_PLIST_DIR, { recursive: true });
    fs.writeFileSync(MACOS_PLIST_PATH, plist, 'utf-8');
}

async function installMacos() {
    writeMacosPlist();
    run(`launchctl load "${MACOS_PLIST_PATH}"`);
    console.log(`${green('✅')} launchd agent installed and started.`);
    await pingService();
}

async function removeMacos() {
    run(`launchctl unload "${MACOS_PLIST_PATH}"`);
    if (fs.existsSync(MACOS_PLIST_PATH)) fs.unlinkSync(MACOS_PLIST_PATH);
    console.log(`${yellow('🗑️')} launchd agent removed.`);
}

async function statusMacos() {
    const r = run(`launchctl list | grep foveai`);
    console.log(r.stdout || 'Service not found in launchctl list.');
    await pingService();
}

// ─── Linux (systemd user) ─────────────────────────────────────────────────────
const LINUX_UNIT_DIR  = path.join(os.homedir(), '.config', 'systemd', 'user');
const LINUX_UNIT_PATH = path.join(LINUX_UNIT_DIR, `${SERVICE_ID}.service`);

function writeLinuxUnit() {
    const unit = `[Unit]
Description=Lumax Solver Guardian — AI error repair service
After=network.target

[Service]
Type=simple
ExecStart=${NODE_BIN} ${SOLVER_JS} --service
Restart=on-failure
RestartSec=5
StandardOutput=append:${os.homedir()}/.foveai/guardian.log
StandardError=append:${os.homedir()}/.foveai/guardian-error.log
Environment=FoveAI_SERVE_PORT=${SERVE_PORT}

[Install]
WantedBy=default.target
`;
    fs.mkdirSync(LINUX_UNIT_DIR, { recursive: true });
    fs.writeFileSync(LINUX_UNIT_PATH, unit, 'utf-8');
}

async function installLinux() {
    writeLinuxUnit();
    run('systemctl --user daemon-reload');
    run(`systemctl --user enable ${SERVICE_ID}`);
    run(`systemctl --user start ${SERVICE_ID}`);
    console.log(`${green('✅')} systemd user service installed and started.`);
    console.log(`   Logs: journalctl --user -u ${SERVICE_ID} -f`);
    await pingService();
}

async function removeLinux() {
    run(`systemctl --user stop ${SERVICE_ID}`);
    run(`systemctl --user disable ${SERVICE_ID}`);
    if (fs.existsSync(LINUX_UNIT_PATH)) fs.unlinkSync(LINUX_UNIT_PATH);
    run('systemctl --user daemon-reload');
    console.log(`${yellow('🗑️')} systemd user service removed.`);
}

async function statusLinux() {
    const r = run(`systemctl --user status ${SERVICE_ID}`);
    console.log(r.stdout || r.stderr || 'Service not found.');
    await pingService();
}

// ─── HTTP Health Ping ─────────────────────────────────────────────────────────
async function pingService() {
    try {
        const resp = await fetch(`http://127.0.0.1:${SERVE_PORT}/health`, { signal: AbortSignal.timeout(3000) });
        if (resp.ok) {
            const data = await resp.json();
            console.log(`\n${green('🛡️  Guardian is LIVE')} on port ${SERVE_PORT}`);
            console.log(`   Auto-apply: ${data.autoApplyEnabled ? green('ENABLED') : yellow('DISABLED (analysis only)')}`);
            console.log(`   Solves logged: ${data.solves}`);
        }
    } catch (_) {
        console.log(`\n${yellow('⚠️  Guardian not responding on port')} ${SERVE_PORT} (may still be starting)`);
    }
}

// ─── Dispatch ─────────────────────────────────────────────────────────────────
export async function install() {
    console.log(`\n🔧 Installing Lumax Solver Guardian as system service (${PLATFORM})…\n`);
    fs.mkdirSync(path.join(os.homedir(), '.foveai'), { recursive: true });
    if (PLATFORM === 'win32')  return installWindows();
    if (PLATFORM === 'darwin') return installMacos();
    if (PLATFORM === 'linux')  return installLinux();
    throw new Error(`Unsupported platform: ${PLATFORM}`);
}

export async function remove() {
    console.log(`\n🗑️  Removing Lumax Solver Guardian (${PLATFORM})…\n`);
    if (PLATFORM === 'win32')  return removeWindows();
    if (PLATFORM === 'darwin') return removeMacos();
    if (PLATFORM === 'linux')  return removeLinux();
    throw new Error(`Unsupported platform: ${PLATFORM}`);
}

export async function status() {
    console.log(`\n🔍 Lumax Solver Guardian status (${PLATFORM})…\n`);
    if (PLATFORM === 'win32')  return statusWindows();
    if (PLATFORM === 'darwin') return statusMacos();
    if (PLATFORM === 'linux')  return statusLinux();
}

export async function start() {
    if (PLATFORM === 'win32')  return startWindows();
    if (PLATFORM === 'darwin') { run(`launchctl start com.foveai.solver`); console.log(green('▶️ Started')); return; }
    if (PLATFORM === 'linux')  { run(`systemctl --user start ${SERVICE_ID}`); console.log(green('▶️ Started')); return; }
}

export async function stop() {
    if (PLATFORM === 'win32')  return stopWindows();
    if (PLATFORM === 'darwin') { run(`launchctl stop com.foveai.solver`); console.log(yellow('⏹️ Stopped')); return; }
    if (PLATFORM === 'linux')  { run(`systemctl --user stop ${SERVICE_ID}`); console.log(yellow('⏹️ Stopped')); return; }
}

// ─── CLI direct invocation ────────────────────────────────────────────────────
const argv = process.argv.slice(2);
if (argv.includes('--install'))  install().catch(e => { console.error('❌', e.message); process.exit(1); });
else if (argv.includes('--remove'))  remove().catch(e => { console.error('❌', e.message); process.exit(1); });
else if (argv.includes('--status'))  status().catch(e => { console.error('❌', e.message); process.exit(1); });
else if (argv.includes('--start'))   start().catch(e => { console.error('❌', e.message); process.exit(1); });
else if (argv.includes('--stop'))    stop().catch(e => { console.error('❌', e.message); process.exit(1); });
