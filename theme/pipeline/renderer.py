import os
from .models import ThemeSpec

class ThemeRenderer:
    @staticmethod
    def generate_css(theme: ThemeSpec) -> str:
        ui = theme.ui_structure
        glass_op = ui.glass_opacity
        
        grid_cols = ui.css_grid_template_columns or "250px 1fr"
        grid_rows = ui.css_grid_template_rows or "1fr"
        grid_areas = ui.css_grid_areas or "'sidebar main'"
        
        # Default colors fallback if optional fields are missing
        accent = theme.fv_accent
        accent_2 = theme.fv_accent_2 or accent
        bg_dark = theme.fv_bg_dark
        bg_panel = theme.fv_bg_panel or "#111111"
        text_main = theme.fv_text_main
        text_muted = theme.fv_text_muted or "#93a1b0"
        danger = theme.fv_danger or "#f87171"
        warn = theme.fv_warn or "#fbbf24"
        ok = theme.fv_ok or "#34d399"
        
        css = f"""/* ══════════════════════════════════════════════════════════════════════════
   FOVEAI AURORA — unified design language
   Theme: {theme.theme_name}
   Generated by Theme Engine Master Webdesigner
   ══════════════════════════════════════════════════════════════════════════ */

:root {{
  /* structural dynamics */
  --fv-menu-position: {ui.menu_position};
  --fv-animation-style: {ui.animation_style};
  --fv-shadow-intensity: {ui.shadow_intensity};
  
  /* Radical CSS Grid */
  --fv-grid-cols: {grid_cols};
  --fv-grid-rows: {grid_rows};
  --fv-grid-areas: {grid_areas};
  
  /* surfaces */
  --fv-bg-dark: {bg_dark};
  --fv-bg-panel: {bg_panel};
  --fv-surface: rgba(148, 163, 184, {glass_op});
  --fv-surface-2: rgba(148, 163, 184, {glass_op + 0.05});
  --fv-glass-top: linear-gradient(180deg, rgba(255,255,255,0.085), rgba(255,255,255,0.025));
  --fv-glass-card: linear-gradient(180deg, rgba(255,255,255,0.05), rgba(255,255,255,0.015));

  /* lines */
  --fv-border: rgba(148, 163, 184, 0.14);
  --fv-border-strong: rgba(148, 163, 184, 0.28);
  --fv-border-accent: {accent}66; /* 40% opacity */

  /* aurora accent ramp */
  --fv-accent: {accent};
  --fv-accent-2: {accent_2};
  --fv-accent-dim: {accent}1f; /* 12% */
  --fv-violet-dim: {accent_2}1f; /* 12% */
  --fv-grad: linear-gradient(92deg, var(--fv-accent) 10%, var(--fv-accent-2) 90%);

  /* ink + text */
  --fv-text: {text_main};
  --fv-muted: {text_muted};
  --fv-danger: {danger};
  --fv-warn: {warn};
  --fv-ok: {ok};

  /* sculpted depth */
  --fv-inset-hi: inset 0 1px 0 rgba(255,255,255,0.09);
  --fv-inset-press: inset 0 2px 6px rgba(0,0,0,0.45);
}}
"""
        return css
