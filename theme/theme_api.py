@app.post("/api/theme/generate")
async def generate_theme(file: UploadFile = File(...)):
    file_path = f"/tmp/{file.filename}"
    with open(file_path, "wb") as f:
        f.write(await file.read())
        
    async def stream_generator():
        # venv python — system python3 lacks pydantic/pipeline deps
        process = await asyncio.create_subprocess_exec(
            sys.executable, "/home/lumba/FoveAI/theme/theme_engine.py", "--apply", file_path,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT
        )

        while True:
            line = await process.stdout.readline()
            if not line:
                break
            yield line.decode('utf-8')

        await process.wait()
        # Post-processing: bind the freshly rendered blueprint to the
        # canonical FUI vocabulary + sound fingerprint from the source image.
        try:
            blueprint = _newest_gallery_theme()
            if blueprint:
                theme = fui_bind_theme(blueprint, image_path=file_path)
                slug = theme.get("theme_name", "fui-theme").lower().replace(" ", "-")[:40]
                out = os.path.join(GALLERY_DIR, f"fui-{slug}-{os.urandom(3).hex()}.json")
                with open(out, "w", encoding="utf-8") as f:
                    json.dump(theme, f, indent=2)
                yield f"\n[FUI] bound + sounded: {out}\n"
        except Exception as e:
            yield f"\n[FUI] bind failed: {e}\n"

    return StreamingResponse(stream_generator(), media_type="text/plain")


@app.get("/api/themes")
async def get_themes():
    gallery_dir = "/home/lumba/FoveAI/theme/gallery"
    themes = []
    if os.path.exists(gallery_dir):
        files = glob.glob(os.path.join(gallery_dir, "*.json"))
        # Sort by file modification time (newest first)
        files.sort(key=os.path.getmtime, reverse=True)
        for fpath in files:
            try:
                with open(fpath, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    themes.append(data)
            except Exception as e:
                print(f"Failed to load {fpath}: {e}")
    return {"themes": themes}



def hex_to_rgb_array(hex_str):
    hex_str = hex_str.lstrip('#')
    if len(hex_str) == 6:
        return [round(int(hex_str[0:2], 16) / 255.0, 3), 
                round(int(hex_str[2:4], 16) / 255.0, 3), 
                round(int(hex_str[4:6], 16) / 255.0, 3)]
    return [1.0, 1.0, 1.0]
