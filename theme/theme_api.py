@app.post("/api/theme/set_active")
async def set_active_theme(theme_spec: ThemeSpec):
    """Saves the globally active theme and broadcasts it to all FoveAI ecosystem clients."""
    theme_data = theme_spec.model_dump()
    with open(ACTIVE_THEME_FILE, "w", encoding="utf-8") as f:
        json.dump(theme_data, f)
        
    # --- UNITY SOFTLAYER INJECTION ---
    try:
        accent = hex_to_rgb_array(theme_data.get('fv_accent', '#328879'))
        bg_dark = hex_to_rgb_array(theme_data.get('fv_bg_dark', '#0182ab'))
        
        unity_js = f"""// 🛸 FOVEAI UNITY SOFTLAYER THEME SYNC 🛸
// Auto-generated by Theme Engine
FoveAI.setParam("lighting.keyLightColor", {accent});
FoveAI.setParam("lighting.fillLightColor", {bg_dark});
// You can map more theme properties to Unity materials here!
FoveAI.log("Global Theme '{theme_data.get('theme_name', 'Unknown')}' applied via SoftLayer!");
"""
        with open("/home/lumba/FoveAI/softlayer/modules/theme_sync.js", "w") as f:
            f.write(unity_js)
    except Exception as e:
        print("Unity softlayer injection failed:", e)

    await manager.broadcast({"type": "theme_update", "theme": theme_data})

    # Relay to the unified WebSocket — the ecosystem port (:8403 IPC server,
    # whose /internal/theme-broadcast fans out to /ws/theme listeners).
    # :8415 stays as the generator/API; clients no longer dial 8415 directly.
    relay = os.getenv("FOVEAI_WS_RELAY_URL", "http://127.0.0.1:8403")
    try:
        import urllib.request
        req = urllib.request.Request(
            f"{relay}/internal/theme-broadcast",
            data=json.dumps({"type": "theme_update", "theme": theme_data}).encode(),
            headers={"Content-Type": "application/json"},
            method="POST",
        )
        await asyncio.get_event_loop().run_in_executor(
            None, lambda: urllib.request.urlopen(req, timeout=5).read()
        )
    except Exception as relay_err:
        print("8403 theme relay failed (broadcast still went out on :8413):", relay_err)

    return {"status": "success", "message": "Theme broadcasted to ecosystem"}



