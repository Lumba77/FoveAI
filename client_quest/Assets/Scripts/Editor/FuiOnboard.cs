using System;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace FoveAI.EditorTools
{
    /// <summary>
    /// Headless Unity onboarding for the FUI canonical theme:
    /// `python3 runtime/fui_colors.py` regenerates assets/fui_palette.json;
    /// this editor method imports it as an Android-safe TextAsset
    /// (Resources/fui_palette.bytes) and saves the project.
    /// Run headless:
    ///   Unity -batchmode -quit -projectPath <proj> -executeMethod FoveAI.EditorTools.FuiOnboard.RunFuiOnboard
    /// </summary>
    public static class FuiOnboard
    {
        // canonical artifact (repo root assets/) — regenerated by the FUI engine
        private const string CanonicalJson =
            "/home/lumba/FoveAI/assets/fui_palette.json";

        private const string ResourcePath = "Assets/Resources/fui_palette.bytes";

        [MenuItem("Spatial Machine/FUI/Import Canonical Palette")]
        public static void ImportFromMenu() => RunFuiOnboard();

        public static void RunFuiOnboard()
        {
            try
            {
                if (!File.Exists(CanonicalJson))
                {
                    Debug.LogError($"[FuiOnboard] canonical palette missing: {CanonicalJson} " +
                                   "— run `python3 runtime/fui_colors.py` first");
                    EditorApplication.Exit(2);
                    return;
                }

                Directory.CreateDirectory("Assets/Resources");
                File.Copy(CanonicalJson, ResourcePath, overwrite: true);

                AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
                var asset = AssetDatabase.LoadAssetAtPath<TextAsset>(ResourcePath);
                if (asset == null)
                {
                    Debug.LogError("[FuiOnboard] import failed — fui_palette.bytes not loadable");
                    EditorApplication.Exit(3);
                    return;
                }

                AssetDatabase.SaveAssets();
                Debug.Log($"[FuiOnboard] ✅ FUI palette imported ({asset.bytes.Length} bytes) — " +
                          "FoveAI.FuiPalette now serves the canonical language.");
                EditorApplication.Exit(0);
            }
            catch (Exception e)
            {
                Debug.LogError($"[FuiOnboard] failed: {e}");
                EditorApplication.Exit(1);
            }
        }
    }
}